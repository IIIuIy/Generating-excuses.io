function normalizeCredibility(value) {
  const raw = (value === '' || value === null || value === undefined) ? 50 : Number(value);
  const n = Number.isFinite(raw) ? raw : 50;
  return clamp(Math.round(n), 1, 100);
}

function tierFor(value) {
  const n = normalizeCredibility(value);
  return TIERS.find(t => n >= t.min && n <= t.max) || TIERS[TIERS.length - 1];
}

function tierById(id) {
  return TIERS.find(t => t.id === id) || null;
}

function allExcuses() {
  const out = [];
  TIERS.forEach(t => t.excuses.forEach((text, i) => out.push({ id: t.id + '-' + i, text: text, tier: t.id })));
  return out;
}

function pick(list, rng) {
  return list[Math.floor(rng() * list.length)];
}

function generateExcuse(value, opts) {
  const options = opts || {};
  const rng = typeof options.rng === 'function' ? options.rng : Math.random;
  const tier = tierFor(value);
  const exclude = new Set(options.exclude || []);
  const pool = tier.excuses.map((text, i) => ({ id: tier.id + '-' + i, text: text }));
  const available = pool.filter(x => !exclude.has(x.id));
  const chosen = pick(available.length ? available : pool, rng);
  const detailed = !!options.detailed && rng() < 0.85;
  const text = chosen.text + (detailed ? ' ' + pick(TAILS, rng) : '');
  return {
    id: chosen.id,
    text: text,
    tier: tier.id,
    tierName: tier.name,
    icon: tier.icon,
    accent: tier.accent,
    detailed: detailed
  };
}

function excuseOfTheDay(date) {
  const d = date instanceof Date ? date : new Date();
  const key = d.getFullYear() + '-' + String(d.getMonth() + 1).padStart(2, '0') + '-' + String(d.getDate()).padStart(2, '0');
  let hash = 0;
  for (let i = 0; i < key.length; i++) hash = (hash * 31 + key.charCodeAt(i)) | 0;
  const all = allExcuses();
  const chosen = all[Math.abs(hash) % all.length];
  const tier = tierById(chosen.tier);
  return { id: 'daily-' + chosen.id, text: chosen.text, tier: tier.id, tierName: tier.name, icon: tier.icon, accent: tier.accent, detailed: false };
}

function searchExcuses(query, limit) {
  const q = String(query == null ? '' : query).trim().toLowerCase();
  if (!q) return [];
  const max = Math.max(1, Math.min(200, Number(limit) || 60));
  return allExcuses().filter(x => x.text.toLowerCase().includes(q)).slice(0, max);
}

function randomCredibility(rng) {
  const r = typeof rng === 'function' ? rng : Math.random;
  return 5 + Math.floor(r() * 91);
}

function summarize(items) {
  const byTier = {};
  TIERS.forEach(t => { byTier[t.id] = 0; });
  (items || []).forEach(item => { if (byTier[item.tier] !== undefined) byTier[item.tier]++; });
  return { total: (items || []).length, byTier: byTier };
}

